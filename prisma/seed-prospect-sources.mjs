/**
 * Заповнює чергу розвідки.
 *
 * Насіння двох типів:
 *   SIMILAR — акаунти з бази розсилок. Це вже перевірений портрет клієнта,
 *             тому «схожі акаунти» від Instagram дають найточніші влучання.
 *   HASHTAG / GEO — ніші та міста, зібрані з наявної бази.
 *
 * Запуск:  DATABASE_URL=... node prisma/seed-prospect-sources.mjs
 */
import { PrismaClient } from "@prisma/client";

const db = new PrismaClient();

// Ніші взяті з реального складу бази: дизайн, ремонт, меблі, стоматології,
// хендмейд, одяг, б'юті, авто, флористика.
const HASHTAGS = [
  "мебліназамовлення", "меблікиїв", "меблільвів", "кухнінавзамовлення", "шафикупе",
  "дизайнінтерєру", "дизайнінтерьєру", "3dвізуалізація", "дизайнерінтерєру",
  "ремонтквартир", "ремонтпідключ", "будівництвобудинків", "натяжністелі",
  "стоматологія", "стоматологіякиїв", "імплантаціязубів", "ортодонт",
  "хендмейдукраїна", "свічкиручноїроботи", "керамікаручноїроботи", "українськийбренд",
  "одягукраїна", "жіночийодяг", "спіднябілизна", "прикрасиручноїроботи",
  "флористика", "квітикиїв", "букети", "барбершоп", "манікюркиїв",
  "автосервіс", "шиномонтаж", "детейлінг",
  "магазинукраїна", "малийбізнесукраїна", "хендмейдпольща", "українцівпольщі",
];

const GEO = [
  "Київ", "Львів", "Дніпро", "Одеса", "Харків", "Вінниця", "Полтава",
  "Тернопіль", "Івано-Франківськ", "Хмельницький", "Чернівці", "Ужгород",
  "Луцьк", "Рівне", "Житомир", "Запоріжжя", "Черкаси", "Миколаїв",
  "Варшава", "Краків", "Вроцлав", "Прага",
];

// Акаунти з найсвіжішими успішними розсилками — вони найрелевантніші як насіння.
const leads = await db.broadcastLead.findMany({
  where: { sendCount: { gt: 0 } },
  orderBy: { lastSentAt: "desc" },
  select: { instagram: true },
});

const rows = [
  ...leads.map((l, i) => ({
    type: "SIMILAR",
    value: l.instagram,
    // Свіжіші отримують вищий пріоритет, щоб обходились першими.
    priority: Math.max(0, 1000 - i),
  })),
  ...HASHTAGS.map((h) => ({ type: "HASHTAG", value: h, priority: 500 })),
  ...GEO.map((g) => ({ type: "GEO", value: g, priority: 400 })),
];

const res = await db.prospectSeed.createMany({ data: rows, skipDuplicates: true });

console.log(`Насіння додано: ${res.count}`);
console.log(`  SIMILAR (з бази розсилок): ${leads.length}`);
console.log(`  HASHTAG: ${HASHTAGS.length}`);
console.log(`  GEO: ${GEO.length}`);

await db.$disconnect();
